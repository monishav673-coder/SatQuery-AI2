/**
 * Apply translations to all [data-i18n] elements on the page.
 * @param {string} lang - language code
 * @param {boolean} save - whether to persist to localStorage
 */
function setLanguage(lang, save = true) {
  if (save) localStorage.setItem('satquery_lang', lang);

  const t = TRANSLATIONS[lang] || TRANSLATIONS.en;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key]) el.textContent = t[key];
  });

  // Update html lang attribute
  document.documentElement.lang = lang;
}

/** Get a translated string by key (falls back to English). */
function t(key) {
  const lang = localStorage.getItem('satquery_lang') || 'en';
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  return dict[key] || TRANSLATIONS.en[key] || key;
}

// Auto-apply on load if lang is stored
(function () {
  const lang = localStorage.getItem('satquery_lang') || 'en';
  // Sync any select elements with id "lang-select" or "nav-lang"
  ['lang-select', 'nav-lang'].forEach(id => {
    const el = document.getElementById(id);
    if (el) el.value = lang;
  });
})();
